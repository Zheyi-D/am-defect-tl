"""Package the repository code into a "self-contained" Kaggle kernel and push it for execution.

How it works: zip src/ configs/ splits/ and the requirements -> embed the archive as base64 in main.py ->
upload to Kaggle (code_file only, so no git clone and no token are needed); at runtime the archive is
extracted and the command is executed.

Usage:
    # smoke test (a single run, 1 epoch, 20 images)
    python tools/build_kernel.py --slug am-defect-smoke \
        --cmd "python -m src.batch --data-root /kaggle/input/datasets/kennethdeng/am-defect-v1 --out results --smoke --limit-runs 1"

    # package only, do not push
    python tools/build_kernel.py --slug am-defect-smoke --no-push
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATASET = "kennethdeng/am-defect-v1"
DEFAULT_DATA_ROOT = "/kaggle/input/datasets/kennethdeng/am-defect-v1"

RUNNER = '''# Auto-generated by tools/build_kernel.py -- self-contained runner
import base64, io, os, shutil, subprocess, sys, zipfile

CODE_B64 = """__CODE_B64__"""
CMD = __CMD_JSON__
WORK = "/kaggle/working"
code_dir = os.path.join(WORK, "code")

try:
    import timm  # noqa: F401
except Exception:
    print("[runner] timm is missing, trying to install it ...", flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "timm"], check=False)

shutil.rmtree(code_dir, ignore_errors=True)
os.makedirs(code_dir, exist_ok=True)
with zipfile.ZipFile(io.BytesIO(base64.b64decode(CODE_B64))) as z:
    z.extractall(code_dir)
os.chdir(code_dir)
sys.path.insert(0, code_dir)

import torch
print("[runner] python:", sys.version.split()[0], flush=True)
print("[runner] torch:", torch.__version__, "cuda:", torch.cuda.is_available(), flush=True)
if torch.cuda.is_available():
    print("[runner] gpu:", torch.cuda.get_device_name(0), flush=True)
print("[runner] cwd:", os.getcwd(), flush=True)
print("[runner] cmd:", CMD, flush=True)

rc = subprocess.run(CMD, shell=True).returncode
print("[runner] exit code:", rc, flush=True)

# Move the results to /kaggle/working/results so kaggle kernels output can download them
# If training already wrote /kaggle/working/results, skip the copy (the paths are the same)
found_any = False
for name in ("results", "results_ablation"):
    src = os.path.join(code_dir, name)
    dst = os.path.join(WORK, name)
    if os.path.isdir(src) and os.path.abspath(src) != os.path.abspath(dst):
        shutil.copytree(src, dst, dirs_exist_ok=True)
    if os.path.isdir(dst):
        found_any = True
        n = sum(len(files) for _, _, files in os.walk(dst))
        print("[runner] output ->", dst, "files:", n, flush=True)
if not found_any:
    print("[runner] WARN: no results/results_ablation dir produced", flush=True)
sys.exit(rc)
'''


def build_zip() -> bytes:
    """Zip the files needed at runtime (excluding data and .git) and record the commit in VERSION."""
    patterns = ["src/*.py", "analysis/*.py", "tools/*.py", "configs/*.yaml", "splits/*.csv", "requirements.txt"]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for pattern in patterns:
            for p in sorted(ROOT.glob(pattern)):
                z.write(p, p.relative_to(ROOT).as_posix())
        try:
            commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                                    cwd=ROOT, capture_output=True, text=True, timeout=5
                                    ).stdout.strip()
        except Exception:
            commit = ""
        z.writestr("VERSION", commit or "unknown")
    return buf.getvalue()


def write_kernel(folder: Path, slug: str, cmd: str, gpu: bool, internet: bool) -> None:
    payload = base64.b64encode(build_zip()).decode("ascii")
    # Inject the command with json.dumps: it may contain quotes, backslashes or non-ASCII text,
    # and plain string concatenation would break the Python syntax
    main_py = RUNNER.replace("__CODE_B64__", payload).replace("__CMD_JSON__", json.dumps(cmd))
    # Compile locally first so syntax errors surface before pushing to Kaggle (saves a GPU run)
    compile(main_py, "main.py", "exec")
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "main.py").write_text(main_py, encoding="utf-8")
    meta = {
        "id": f"kennethdeng/{slug}",
        "title": slug,
        "code_file": "main.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": gpu,
        "enable_internet": internet,
        "dataset_sources": [DATASET],
        "competition_sources": [],
        "kernel_sources": [],
    }
    (folder / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")


def push(folder: Path) -> int:
    exe = shutil.which("kaggle") or "kaggle"
    print(f"[kernel] push {folder} ...", flush=True)
    return subprocess.run([exe, "kernels", "push", "-p", str(folder)]).returncode


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--slug", required=True, help="Kaggle kernel slug, e.g. am-defect-smoke")
    ap.add_argument("--cmd", default=(
        f"python -m src.batch --data-root {DEFAULT_DATA_ROOT} --out results --smoke --limit-runs 1"))
    ap.add_argument("--no-gpu", action="store_true")
    ap.add_argument("--no-internet", action="store_true")
    ap.add_argument("--no-push", action="store_true")
    ap.add_argument("--keep", action="store_true", help="keep the build directory")
    args = ap.parse_args()

    folder = ROOT / "kaggle" / args.slug
    write_kernel(folder, args.slug, args.cmd, gpu=not args.no_gpu, internet=not args.no_internet)
    size_kb = (folder / "main.py").stat().st_size / 1024
    print(f"[kernel] build complete: {folder}  main.py={size_kb:.0f} KB", flush=True)

    if args.no_push:
        return
    rc = push(folder)
    if not args.keep:
        print(f"[kernel] build artifacts kept in {folder} (for review; safe to delete manually)", flush=True)
    sys.exit(rc)


if __name__ == "__main__":
    main()
